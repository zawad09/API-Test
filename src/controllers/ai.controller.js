/**
 * AI Career Coach controller.
 *
 * Both endpoints load an analysis the user OWNS (404 unknown / 403 not yours -
 * exactly the same ownership rules as the analysis endpoints), then ask the
 * ai.service to produce the text. The service either calls the configured AI
 * provider (source: "ai") or falls back to the deterministic rule-based coach
 * (source: "rule-based") - so these endpoints always answer 200.
 */
const ApiResponse = require('../utils/ApiResponse');
const asyncHandler = require('../utils/asyncHandler');
const analysisService = require('../services/analysis.service');
const aiService = require('../services/ai.service');

/** POST /api/ai/explain/:analysisId - natural-language explanation of one analysis */
const explainAnalysis = asyncHandler(async (req, res) => {
  const analysis = await analysisService.getAnalysisById(req.user._id, req.params.analysisId);
  const { source, explanation } = await aiService.generateExplanation(analysis, analysis.job);

  return ApiResponse.success(res, {
    statusCode: 200,
    message:
      source === 'ai'
        ? 'AI explanation generated successfully'
        : 'Explanation generated by the built-in rule-based coach (AI is disabled, not configured, or unavailable)',
    data: {
      analysisId: analysis._id,
      jobTitle: analysis.job?.title,
      overallMatchPercentage: analysis.overallMatchPercentage,
      source,
      explanation,
      generatedAt: new Date().toISOString(),
    },
  });
});

/** POST /api/ai/roadmap/:analysisId - week-by-week learning roadmap for one analysis */
const buildRoadmap = asyncHandler(async (req, res) => {
  const analysis = await analysisService.getAnalysisById(req.user._id, req.params.analysisId);
  const { source, roadmap } = await aiService.generateRoadmap(analysis, analysis.job);

  return ApiResponse.success(res, {
    statusCode: 200,
    message:
      source === 'ai'
        ? 'AI roadmap generated successfully'
        : 'Roadmap generated by the built-in rule-based coach (AI is disabled, not configured, or unavailable)',
    data: {
      analysisId: analysis._id,
      jobTitle: analysis.job?.title,
      overallMatchPercentage: analysis.overallMatchPercentage,
      source,
      roadmap,
      generatedAt: new Date().toISOString(),
    },
  });
});

module.exports = { explainAnalysis, buildRoadmap };
